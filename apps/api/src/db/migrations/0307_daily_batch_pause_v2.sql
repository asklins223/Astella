-- 0307 —— **「暂停今天这一批」落在 0305 那一行上**（39d W7-4 刀十一；39 §12 表「今日复习」行）。
--
-- 刀十落了三个动作的**判据**（减量／暂停／恢复，其中「暂停**不改长度**」是刻意的），
-- 但**暂停还没有地方可落**——0305 那一行只有长度与加量，没有「现在停着」这一档。
-- 于是暂停只能活在渲染层的内存里，刷新一次就没了，而"她说过先停一下"是**她刚做过
-- 的一个决定**。
--
-- 为什么落在 **0305 那一行**而不是新表：暂停的是**今天这一批**，而"今天这一批"就是
-- 0305 那一行。分成两张表就要在两处各存一次"今天"这个键，而两处的键一旦算得不一致
-- （一处按她的日历日、一处按 UTC），暂停就会**对不上批次**。
--
-- **只加一个可空的时刻**，不加状态枚举：暂停 = 这一时刻非空，恢复 = 置空。
-- 枚举要多一套"未知/已停/在跑"的迁移，而那三态在结构上是同一个问题——**现在停着
-- 吗**。加 `paused_at` 还能白拿到"她什么时候停的"（屏上与审计都要）。
--
-- 刻意的约束（写在 CHECK 里而不是靠读侧自觉）：**暂停不减长度**。刀十的判据说
-- "暂停不改长度"，而如果这一列允许 `paused_at IS NOT NULL AND locked_length <> …`，
-- 判据那一格就成了摆设——停一次再恢复，那一批就短一截，**而她什么也没少做**。
ALTER TABLE daily_review_batches_v2
  ADD COLUMN IF NOT EXISTS paused_at timestamptz;

COMMENT ON COLUMN daily_review_batches_v2.paused_at IS
  '39 §12.1 表「今日复习」行的「暂停」。非空 = 今天这一批现在停着；置空 = 接着做。与 locked_length 无关：暂停不减长度（刀十的判据）。';
